def unconditional_system_outcomes(
    outcomes: Sequence[EpisodeOutcome],
) -> list[EpisodeOutcome]:
    """Convert Profile-I initializer failures to complete-system utility-zero attempts.

    Policy-learning analyses keep initializer failures outside the conditional episode
    population.  An external whole-system comparison has a different estimand: every sealed
    task/repetition attempt counts, so failure to initialize is exactly utility zero.  This
    explicit conversion prevents the conditional and unconditional estimands from being
    silently mixed.
    """

    converted: list[EpisodeOutcome] = []
    for outcome in outcomes:
        outcome.validate_receipt(require_complete=True)
        if outcome.outcome_kind == INITIALIZATION_FAILURE:
            unconditional = replace(
                outcome,
                utility=0.0,
                reason=f"INITIALIZATION_FAILURE_ZERO:{outcome.reason}",
                outcome_kind=TASK_TERMINAL,
                population_eligible=True,
            )
            unconditional.validate_receipt(require_complete=True)
            converted.append(unconditional)
        else:
            converted.append(outcome)
    return converted


def write_external_attempt_receipts(
    path: str | os.PathLike[str],
    receipts: Sequence[ExternalAttemptReceipt],
    *,
    overwrite: bool = False,
) -> str:
    """Atomically write canonical detailed JSONL and return its file SHA-256."""

    if not receipts:
        raise EvaluationProtocolError("cannot write an empty external receipt batch")
    keys = [(item.lineage, item.instance, item.repetition) for item in receipts]
    if len(keys) != len(set(keys)):
        raise EvaluationProtocolError("external receipt batch contains duplicate pair keys")
    rows = sorted(receipts, key=lambda item: (item.lineage, item.instance, item.repetition))
    content = b"".join(
        (
            json.dumps(
                item.as_dict(),
                sort_keys=True,
                separators=(",", ":"),
                allow_nan=False,
            )
            + "\n"
        ).encode("utf-8")
        for item in rows
    )
    digest = hashlib.sha256(content).hexdigest()
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists() and not overwrite:
        raise FileExistsError(destination)
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{destination.name}.", suffix=".tmp", dir=destination.parent
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        if overwrite:
            os.replace(temporary, destination)
        else:
            try:
                os.link(temporary, destination)
            except FileExistsError:
                raise FileExistsError(destination) from None
            temporary.unlink()
    finally:
        temporary.unlink(missing_ok=True)
    return digest


