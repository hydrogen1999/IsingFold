"""Outcome-blind complete-system baselines outside the shared IsingFold action support.

The stock-minorminer adapter is optional and imported only inside an isolated worker.  Its
native search is compared as a complete system under a preregistered wall-clock/restart
budget; it is never inserted into the same-support causal ablations in :mod:`evaluate`.

The backend protocol is intentionally small enough for a future native OCT or ATOM adapter,
but only stock minorminer is registered.  Missing implementations are reported as missing;
this module never fabricates their outputs.
"""

