class ExternalBackendError(RuntimeError):
    """A backend/protocol fault, which must not be converted into a zero utility."""


class ExternalBackendStartupTimeout(TimeoutError):
    """The isolated publication worker could not start inside the total deadline."""


def stock_minorminer_artifact_manifest(*, expected_version: str) -> dict[str, object]:
    """Hash the installed stock-minorminer code and native artifacts.

    A distribution version alone is not an implementation identity: locally rebuilt wheels can
    retain the same version.  Generated bytecode and licenses are deliberately excluded, while
    Python/Cython/C/C++ sources, headers, native extensions, and wheel metadata are included.
    """

    distribution = importlib_metadata.distribution("minorminer")
    version = distribution.version
    if version != expected_version:
        raise ExternalBackendError(
            f"installed minorminer version {version!r} differs from registered "
            f"version {expected_version!r}"
        )
    files = distribution.files
    if files is None:
        raise ExternalBackendError("minorminer distribution exposes no installed-file registry")
    records: list[dict[str, object]] = []
    for entry in sorted(files, key=str):
        relative = Path(str(entry))
        if relative.is_absolute() or ".." in relative.parts:
            raise ExternalBackendError("minorminer distribution contains an unsafe file path")
        if relative.suffix.lower() not in _STOCK_CODE_SUFFIXES and relative.name not in (
            _STOCK_METADATA_FILES
        ):
            continue
        source = Path(distribution.locate_file(entry))
        if not source.is_file():
            raise ExternalBackendError(
                f"registered minorminer artifact is missing: {relative.as_posix()}"
            )
        content = source.read_bytes()
        records.append(
            {
                "path": relative.as_posix(),
                "sha256": hashlib.sha256(content).hexdigest(),
                "size_bytes": len(content),
            }
        )
    if not records or not any(
        Path(str(record["path"])).suffix.lower() in {".so", ".pyd", ".dylib", ".dll"}
        for record in records
    ):
        raise ExternalBackendError(
            "minorminer artifact registry does not contain its native extension"
        )
    payload: dict[str, object] = {
        "schema": STOCK_MINORMINER_ARTIFACT_SCHEMA,
        "schema_version": STOCK_MINORMINER_ARTIFACT_VERSION,
        "distribution": "minorminer",
        "distribution_version": version,
        "selection": "code-source-header-native-extension-and-wheel-metadata-v1",
        "files": records,
        "file_count": len(records),
    }
    return {**payload, "record_digest": stable_digest(payload)}


class SearchStatus(str, Enum):
    EMBEDDING = "EMBEDDING"
    NO_EMBEDDING = "NO_EMBEDDING"
    TIMED_OUT = "TIMED_OUT"
    ERROR = "ERROR"


@dataclass(frozen=True)
class BackendIdentity:
    """Versioned identity of one native external embedder implementation."""

    method_id: str
    distribution: str
    version: str
    entrypoint: str
    implementation: str

    def __post_init__(self) -> None:
        for name in self.__dataclass_fields__:
            value = getattr(self, name)
            if not isinstance(value, str) or not value:
                raise ValueError(f"backend identity {name} must be a nonempty string")

    def as_dict(self) -> dict[str, str]:
        return {name: getattr(self, name) for name in self.__dataclass_fields__}


@dataclass(frozen=True)
class BackendAvailability:
    available: bool
    reason: str
    identity: BackendIdentity | None = None

    def __post_init__(self) -> None:
        if type(self.available) is not bool or not self.reason:
            raise ValueError("backend availability needs a Boolean status and reason")
        if self.available != (self.identity is not None):
            raise ValueError("available backend must have an identity and unavailable one must not")

    def as_dict(self) -> dict[str, object]:
        return {
            "available": self.available,
            "reason": self.reason,
            "identity": None if self.identity is None else self.identity.as_dict(),
        }


@dataclass(frozen=True)
class BackendSearchResult:
    """One isolated native call, before independent IsingFold validation."""

    status: SearchStatus
    embedding: Mapping[Hashable, Sequence[Hashable]] | None
    elapsed_seconds: float = field(compare=False)
    detail: str = ""

    def __post_init__(self) -> None:
        object.__setattr__(self, "status", SearchStatus(self.status))
        if (
            isinstance(self.elapsed_seconds, bool)
            or not math.isfinite(self.elapsed_seconds)
            or self.elapsed_seconds < 0.0
        ):
            raise ValueError("backend elapsed time must be finite and nonnegative")
        if self.status is SearchStatus.EMBEDDING and self.embedding is None:
            raise ValueError("EMBEDDING status requires an embedding payload")
        if self.status is not SearchStatus.EMBEDDING and self.embedding is not None:
            raise ValueError("non-embedding status cannot carry an embedding payload")
        if not isinstance(self.detail, str):
            raise ValueError("backend result detail must be a string")


